"""Generate native Direct2D geometry from the same SVG icons as the Web UI.
Run: python scripts/generate-native-icons.py (standard library only).
"""
from pathlib import Path
import re, math, hashlib, xml.etree.ElementTree as ET
root=Path(__file__).resolve().parents[1]
source=(root/'src/capture-icons.ts').read_text(encoding='utf-8')
def n(v):
    v=0 if abs(v)<1e-6 else v
    text=f'{v:.6f}'.rstrip('0').rstrip('.')
    return text if '.' in text else text+'.0'

def cmd(kind,values=()):return kind+'('+','.join(n(v) for v in values)+')' if values else kind

def arc(x,y,rx,ry,phi,large,sweep,ex,ey):
    rx,ry=abs(rx),abs(ry)
    if rx==0 or ry==0:return [cmd('L',(ex,ey))]
    if abs(ex-x)+abs(ey-y)<1e-9:return []
    phi=math.radians(phi);c,s=math.cos(phi),math.sin(phi)
    dx,dy=(x-ex)/2,(y-ey)/2;xp,yp=c*dx+s*dy,-s*dx+c*dy
    q=xp*xp/(rx*rx)+yp*yp/(ry*ry)
    if q>1:rx*=math.sqrt(q);ry*=math.sqrt(q)
    factor=math.sqrt(max(0,(rx*rx*ry*ry-rx*rx*yp*yp-ry*ry*xp*xp)/(rx*rx*yp*yp+ry*ry*xp*xp)))
    if bool(large)==bool(sweep):factor=-factor
    cxp,cyp=factor*rx*yp/ry,-factor*ry*xp/rx
    cx,cy=c*cxp-s*cyp+(x+ex)/2,s*cxp+c*cyp+(y+ey)/2
    ux,uy=(xp-cxp)/rx,(yp-cyp)/ry;vx,vy=(-xp-cxp)/rx,(-yp-cyp)/ry
    start=math.atan2(uy,ux);delta=math.atan2(ux*vy-uy*vx,ux*vx+uy*vy)
    if sweep and delta<0:delta+=2*math.pi
    if not sweep and delta>0:delta-=2*math.pi
    count=math.ceil(abs(delta)/(math.pi/2));result=[]
    def p(t):return (cx+c*rx*math.cos(t)-s*ry*math.sin(t),cy+s*rx*math.cos(t)+c*ry*math.sin(t))
    def d(t):return (-c*rx*math.sin(t)-s*ry*math.cos(t),-s*rx*math.sin(t)+c*ry*math.cos(t))
    for i in range(count):
        a=start+i*delta/count;b=start+(i+1)*delta/count;k=4/3*math.tan((b-a)/4)
        p1,p2,d1,d2=p(a),p(b),d(a),d(b)
        result.append(cmd('C',(p1[0]+k*d1[0],p1[1]+k*d1[1],p2[0]-k*d2[0],p2[1]-k*d2[1],*p2)))
    return result

def path(data):
    tokens=re.findall(r'[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?',data)
    i=0;op='';x=y=sx=sy=0;result=[];previous=None
    counts={'M':2,'L':2,'H':1,'V':1,'C':6,'S':4,'Q':4,'A':7}
    while i<len(tokens):
        if tokens[i].isalpha():op=tokens[i];i+=1
        upper=op.upper();relative=op.islower()
        if upper=='Z':result.append('Z');x,y=sx,sy;op='';previous=None;continue
        assert upper in counts,upper
        values=list(map(float,tokens[i:i+counts[upper]]));i+=counts[upper]
        def xy(a,b):return (a+x,b+y) if relative else (a,b)
        if upper in ('M','L'):
            x,y=xy(*values);result.append(cmd(upper,(x,y)))
            if upper=='M':sx,sy=x,y;op='l' if relative else 'L'
        elif upper=='H':x=values[0]+x if relative else values[0];result.append(cmd('L',(x,y)))
        elif upper=='V':y=values[0]+y if relative else values[0];result.append(cmd('L',(x,y)))
        elif upper=='C':
            a,b,e=xy(*values[:2]),xy(*values[2:4]),xy(*values[4:]);result.append(cmd('C',(*a,*b,*e)));previous=b;x,y=e
        elif upper=='S':
            a=(2*x-previous[0],2*y-previous[1]) if previous else (x,y);b,e=xy(*values[:2]),xy(*values[2:]);result.append(cmd('C',(*a,*b,*e)));previous=b;x,y=e
        elif upper=='Q':
            a,e=xy(*values[:2]),xy(*values[2:]);result.append(cmd('C',(x+2*(a[0]-x)/3,y+2*(a[1]-y)/3,e[0]+2*(a[0]-e[0])/3,e[1]+2*(a[1]-e[1])/3,*e)));x,y=e
        elif upper=='A':
            e=xy(*values[-2:]);result+=arc(x,y,*values[:5],*e);x,y=e
        if upper not in ('C','S'):previous=None
    return ','.join(result)

out=['// Generated by scripts/generate-native-icons.py. Do not edit.', '// SVG SHA256: '+hashlib.sha256(source.encode()).hexdigest(), 'use super::native_icons::{Shape,Cmd::*};', 'pub(super) const ICONS: &[(&str,&[Shape])] = &[']
for name,markup in re.findall(r"^\s*(\w+): '([^']*)',",source,re.M):
    shapes=[]
    for node in ET.fromstring('<svg>'+markup+'</svg>'):
        a=node.attrib;fill=a.get('fill')=='currentColor';stroke=0 if a.get('stroke')=='none' else float(a.get('stroke-width','1.7'))
        if node.tag=='path':shape='Shape::Path(&['+path(a['d'])+'],'+str(fill).lower()+','+n(stroke)+')'
        elif node.tag=='rect':shape='Shape::Rect('+','.join(n(float(a.get(k,0))) for k in ['x','y','width','height','rx'])+','+str(fill).lower()+','+n(stroke)+')'
        elif node.tag in ('ellipse','circle'):
            values=[float(a['cx']),float(a['cy']),float(a.get('rx',a.get('r'))),float(a.get('ry',a.get('r')))];shape='Shape::Ellipse('+','.join(map(n,values))+','+str(fill).lower()+','+n(stroke)+')'
        else:raise ValueError(node.tag)
        shapes.append(shape)
    out.append('    ("'+name+'",&['+','.join(shapes)+']),')
out.append('];\n')
(root/'src-tauri/src/native_icon_data.rs').write_text('\n'.join(out),encoding='utf-8')
print('Generated shared native SVG icons')
